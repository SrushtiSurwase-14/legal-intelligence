"""Run the evaluation set against the real pipeline and compare with the expected behaviour.

    python evaluation/run_eval.py            # prints a table, writes evaluation/results.json
    python evaluation/run_eval.py --reports  # also (re)writes docs/evaluation_report.md and docs/evidence_report.md

The expectations in questions.json were written BEFORE looking at outputs where possible; failures are
reported honestly (exit code 1), never edited away.
"""
from __future__ import annotations

import json
import logging
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.config import Settings  # noqa: E402
from app.models import ResearchRequest  # noqa: E402
from app.service import LegalIntelligenceService  # noqa: E402

FIXED_TODAY = date(2026, 10, 22)  # pins "today" so results are reproducible on any day
CONCLUSION = {"VERIFIED", "SOURCE_DERIVED", "INTERPRETATION"}
_services: dict = {}


def service_for(case: dict) -> LegalIntelligenceService:
    key = case.get("simulate_failure")
    if key not in _services:
        _services[key] = LegalIntelligenceService(Settings.from_env(
            today=FIXED_TODAY, trace_dir=None, simulate_failure=key, log_level="ERROR",
            analyzer_mode="extractive"))
    return _services[key]


def check(case: dict, r) -> list[str]:
    x, bad = case["expect"], []
    codes = {l.code.value for l in r.limitations}
    docs = {e.doc_id for e in r.evidence}
    labels = {s.label.value for s in r.analysis.analysis}
    if r.status.value not in x["status_in"]:
        bad.append(f"status {r.status.value} not in {x['status_in']}")
    for d in x.get("evidence_docs_include", []):
        if d not in docs:
            bad.append(f"evidence missing doc {d}")
    for c in x.get("limitation_codes_include", []):
        if c not in codes:
            bad.append(f"limitation {c} missing")
    if "confidence_in" in x and r.confidence not in x["confidence_in"]:
        bad.append(f"confidence {r.confidence} not in {x['confidence_in']}")
    if "evidence_count" in x and len(r.evidence) != x["evidence_count"]:
        bad.append(f"evidence count {len(r.evidence)} != {x['evidence_count']}")
    for rel in x.get("version_relations_include", []):
        if rel not in {n.relation for n in r.version_notes}:
            bad.append(f"version relation {rel} not exposed")
    for q in x.get("quote_contains", []):
        if not any(q in e.quote for e in r.evidence):
            bad.append(f"no evidence quote contains {q!r}")
    for s in x.get("statuses_include", []):
        if s not in {e.provision_status for e in r.evidence}:
            bad.append(f"no evidence with provision status {s}")
    if x.get("assumption_present") and not r.question_analysis.assumptions:
        bad.append("assumption not stated")
    if "requires_review" in x and r.analysis.requires_professional_review != x["requires_review"]:
        bad.append(f"requires_review {r.analysis.requires_professional_review} != {x['requires_review']}")
    for l in x.get("analysis_labels_include", []):
        if l not in labels:
            bad.append(f"analysis label {l} missing")
    for l in x.get("analysis_labels_exclude", []):
        if l in labels:
            bad.append(f"analysis label {l} must not appear")
    if x.get("no_conclusion") and (labels & CONCLUSION):
        bad.append("a conclusion-type statement was produced without evidence")
    if "failed_step" in x and not any(s.status == "failed" and s.name == x["failed_step"] for s in r.steps):
        bad.append(f"step {x['failed_step']} not shown as failed")
    if "generated_by" in x and r.analysis.generated_by != x["generated_by"]:
        bad.append(f"generated_by {r.analysis.generated_by} != {x['generated_by']}")
    if any(not e.verified for e in r.evidence):
        bad.append("unverified evidence present")
    return bad


def run(cases_path: Path = ROOT / "evaluation" / "questions.json") -> list[dict]:
    logging.getLogger("li").setLevel(logging.ERROR)
    out = []
    for case in json.loads(cases_path.read_text(encoding="utf-8")):
        req = ResearchRequest(question=case["question"], jurisdiction=case.get("jurisdiction"),
                              as_of_date=case.get("as_of_date"), facts=case.get("facts", {}))
        r = service_for(case).analyze(req)
        problems = check(case, r)
        out.append({"case": case, "response": r, "problems": problems, "passed": not problems})
    return out


def write_reports(results: list[dict]) -> None:
    (ROOT / "docs").mkdir(exist_ok=True)
    n, ok = len(results), sum(r["passed"] for r in results)
    L = ["# Evaluation report", "",
         f"*Generated by `python evaluation/run_eval.py --reports` with `today` pinned to {FIXED_TODAY}. "
         "Corpus: the fictional sample documents in `data/corpus` - results say nothing about real law.*", "",
         f"**{ok} of {n} evaluation questions behaved as expected.**", "",
         "| ID | Category | Difficulty | Status | Confidence | Limitation codes | Result |", "|---|---|---|---|---|---|---|"]
    for r in results:
        c, resp = r["case"], r["response"]
        codes = ", ".join(sorted({l.code.value for l in resp.limitations})) or "-"
        L.append(f"| {c['id']} | {c['category']} | {c['difficulty']} | {resp.status.value} | {resp.confidence} | "
                 f"{codes} | {'PASS' if r['passed'] else 'FAIL: ' + '; '.join(r['problems'])} |")
    (ROOT / "docs" / "evaluation_report.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    E = ["# Evidence report - integrated demonstrations (Tests A-E)", "",
         f"*Generated from real runs by `python evaluation/run_eval.py --reports` (today pinned to {FIXED_TODAY}).* "
         "*The corpus is fictional (Freedonia); no real law is cited.*", ""]
    for r in sorted((x for x in results if x["case"].get("demo")), key=lambda x: x["case"]["demo"]):
        c, resp = r["case"], r["response"]
        E += [f"## Test {c['demo']} - {c['category'].replace('_', ' ')} ({c['id']})", "",
              f"**Question:** {c['question']}" + (f"  \n**Request options:** jurisdiction={c.get('jurisdiction')}, "
                                                   f"as_of_date={c.get('as_of_date')}" if c.get("jurisdiction") or c.get("as_of_date") else "")
              + (f"  \n**Injected failure:** `{c['simulate_failure']}`" if c.get("simulate_failure") else ""), "",
              f"**Expected behaviour:** {c['expected_behaviour']}", "",
              f"**Actual behaviour:** status `{resp.status.value}`, confidence `{resp.confidence}`, "
              f"professional review required: `{resp.analysis.requires_professional_review}`.  ",
              f"Answer summary: {resp.answer_summary}", "",
              f"**Result:** {'PASS' if r['passed'] else 'FAIL - ' + '; '.join(r['problems'])}", "", "**Sources:**"]
        used = [s for s in resp.analysis.relevant_sources]
        E += [f"- `{s.doc_id}` - {s.title} ({s.role.value}; v{s.version}; effective {s.effective_date}; "
              f"status {s.amendment_status}) - *{s.used_as}*" for s in used] or ["- none"]
        E += ["", "**Evidence (verbatim, verified against source text):**"]
        E += [f"- [{e.evidence_id}] `{e.doc_id}` {e.section} ({e.provision_status}, {e.purpose}): \"{e.quote}\""
              for e in resp.evidence] or ["- none (by design)"]
        E += ["", "**Limitations reported:**"]
        E += [f"- `{l.code.value}` ({l.severity}): {l.message}" for l in resp.limitations] or ["- none"]
        E += ["", "**Pipeline steps:** " + " -> ".join(f"{s.name}:{s.status}" for s in resp.steps), "",
              f"**Trace id:** `{resp.trace_id}` (changes every run).", "",
              "**Known limitation of this demonstration:** runs on a small fictional corpus with lexical retrieval; "
              "see README 'Known limitations'.", ""]
    (ROOT / "docs" / "evidence_report.md").write_text("\n".join(E), encoding="utf-8")


if __name__ == "__main__":
    res = run()
    for r in res:
        print(f"{r['case']['id']} {'PASS' if r['passed'] else 'FAIL'}  {r['case']['category']:<38} "
              f"{r['response'].status.value:<22} {'; '.join(r['problems'])}")
    print(f"\n{sum(r['passed'] for r in res)}/{len(res)} passed")
    (ROOT / "evaluation" / "results.json").write_text(json.dumps(
        [{"id": r["case"]["id"], "passed": r["passed"], "problems": r["problems"],
          "response": json.loads(r["response"].model_dump_json())} for r in res], indent=1), encoding="utf-8")
    if "--reports" in sys.argv:
        write_reports(res)
        print("reports written to docs/")
    sys.exit(0 if all(r["passed"] for r in res) else 1)
