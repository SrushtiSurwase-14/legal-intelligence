"""Run pytest and write docs/test_report.md with the REAL numbers (total / passed / failed / skipped)."""
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
xml = ROOT / "logs" / "junit.xml"
xml.parent.mkdir(exist_ok=True)
proc = subprocess.run([sys.executable, "-m", "pytest", f"--junitxml={xml}", "-q"], cwd=ROOT,
                      capture_output=True, text=True, env={"PYTHONPATH": str(ROOT), "PATH": "/usr/bin:/bin:/usr/local/bin"})
suite = ET.parse(xml).getroot()
suite = suite if suite.tag == "testsuite" else suite[0]
total, fail, err, skip = (int(suite.get(k, 0)) for k in ("tests", "failures", "errors", "skipped"))
passed = total - fail - err - skip
by_file: dict[str, list[int]] = {}
skipped_names = []
for tc in suite.iter("testcase"):
    f = tc.get("classname", "").split(".")[-1]
    row = by_file.setdefault(f, [0, 0, 0, 0])
    row[0] += 1
    if tc.find("failure") is not None or tc.find("error") is not None:
        row[2] += 1
    elif tc.find("skipped") is not None:
        row[3] += 1
        skipped_names.append(f"{f}::{tc.get('name')}")
    else:
        row[1] += 1
L = ["# Test report", "",
     f"*Generated by `python scripts/make_test_report.py` on {datetime.now():%Y-%m-%d %H:%M} with Python "
     f"{sys.version.split()[0]}. Re-run it on your own machine; do not trust a number you did not reproduce.*", "",
     "| Total | Passed | Failed | Errors | Skipped |", "|---|---|---|---|---|",
     f"| {total} | {passed} | {fail} | {err} | {skip} |", "", "## By file", "",
     "| File | Tests | Passed | Failed | Skipped |", "|---|---|---|---|---|"]
for f, (t, p, x, s) in sorted(by_file.items()):
    L.append(f"| {f} | {t} | {p} | {x} | {s} |")
L += ["", "## Skipped tests (and why)", ""]
L += [f"- `{n}` - needs the optional `sentence-transformers` package (experimental hybrid retriever); not run in "
      "the default environment." for n in skipped_names] or ["- none"]
L += ["", "## What the tests do NOT cover (known limitations)", "",
      "- Retrieval quality on real, long, messy legal documents (the sample corpus is 7 short fictional documents).",
      "- The real LLM: tests use a fake model to check the *validation* around it; `AnthropicLLM` was never run "
      "against the live API in the build environment.",
      "- The hybrid (embedding) retriever and `scripts/pdf_to_text.py` (optional, untested here).",
      "- Concurrency/load, authentication, and rate limiting (not implemented).",
      "- Legal correctness: nothing here verifies real law; the sample documents are fictional.", ""]
(ROOT / "docs" / "test_report.md").write_text("\n".join(L), encoding="utf-8")
print(f"total={total} passed={passed} failed={fail} errors={err} skipped={skip}")
sys.exit(0 if (fail + err) == 0 else 1)
